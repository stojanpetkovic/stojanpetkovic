#!/usr/bin/env python3
"""
Build the outline and the relief of the model from two open data sets:

  * the boundary of AP Vojvodina from OpenStreetMap, as GeoJSON
        curl -A "<your agent>" "https://nominatim.openstreetmap.org/search?q=Vojvodina&countrycodes=rs&format=geojson&polygon_geojson=1&polygon_threshold=0.0005&limit=1" -o vojvodina.json
  * elevation tiles from Terrain Tiles on AWS (terrarium encoding, zoom 8)
        https://s3.amazonaws.com/elevation-tiles-prod/terrarium/8/<x>/<y>.png   x 141..143, y 90..92

and write `src/lib/geothermal/outline.ts` and `src/lib/geothermal/terrain-data.ts`.

    python3 scripts/build-terrain-data.py vojvodina.json tiles/

`tiles/` holds the nine files as t_8_<x>_<y>.png. Needs numpy, scipy, matplotlib and Pillow.
"""
import base64
import math
import sys

import numpy as np
from PIL import Image

import json

BOUNDARY, TILES = sys.argv[1], sys.argv[2]
LAT0, LON0 = 45.4, 20.0            # origin of the local coordinates, as ORIGIN in field.ts
KM_LAT = 111.13
KM_LON = 111.32 * math.cos(math.radians(LAT0))
Z = 8
CELL = 1.0                          # km
STEP = 3.0                          # metres per byte


def project(lat, lon):
    return (lon - LON0) * KM_LON, (lat - LAT0) * KM_LAT


def unproject(x, y):
    return LAT0 + y / KM_LAT, LON0 + x / KM_LON


def simplify(pts, tol):
    """Douglas-Peucker."""
    if len(pts) < 3:
        return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = math.hypot(dx, dy) or 1e-9
    d = [abs(dy * (x - x1) - dx * (y - y1)) / norm for x, y in pts[1:-1]]
    k = int(np.argmax(d)) + 1
    if d[k - 1] <= tol:
        return [pts[0], pts[-1]]
    return simplify(pts[:k + 1], tol)[:-1] + simplify(pts[k:], tol)


# ── Outline ──────────────────────────────────────────────────────────────────
geo = json.load(open(BOUNDARY))['features'][0]['geometry']
polys = geo['coordinates'] if geo['type'] == 'MultiPolygon' else [geo['coordinates']]
rings = []
for poly in polys:
    ring = [project(lat, lon) for lon, lat in poly[0]][:-1]
    ring = simplify(ring, 0.25)
    rings.append([(round(x, 2), round(y, 2)) for x, y in ring])
rings.sort(key=lambda r: -len(r))
xs = [p[0] for r in rings for p in r]
ys = [p[1] for r in rings for p in r]
print('outline rings', [len(r) for r in rings], 'bbox', min(xs), max(xs), min(ys), max(ys))

with open('src/lib/geothermal/outline.ts', 'w') as f:
    f.write('''/**
 * Outline of AP Vojvodina: the shape of the model. Rings of points in local kilometres,
 * east and north of the model origin (see `ORIGIN` in field.ts).
 *
 * The boundary is from OpenStreetMap (© OpenStreetMap contributors, ODbL), simplified
 * to 250 m. Generated by `scripts/build-terrain-data.py`; do not edit by hand.
 */

export const OUTLINE: [number, number][][] = [
''')
    for ring in rings:
        f.write('  [\n' + ''.join(f'    [{x}, {y}],\n' for x, y in ring) + '  ],\n')
    f.write('];\n')

# ── Relief ───────────────────────────────────────────────────────────────────
tiles = {}
xt = sorted({int(n.split('_')[2]) for n in __import__('os').listdir(TILES) if n.startswith('t_')})
yt = sorted({int(n.split('_')[3].split('.')[0]) for n in __import__('os').listdir(TILES) if n.startswith('t_')})
mosaic = np.zeros((len(yt) * 256, len(xt) * 256))
for i, tx in enumerate(xt):
    for j, ty in enumerate(yt):
        a = np.array(Image.open(f'{TILES}/t_{Z}_{tx}_{ty}.png').convert('RGB')).astype(float)
        mosaic[j * 256:(j + 1) * 256, i * 256:(i + 1) * 256] = a[:, :, 0] * 256 + a[:, :, 1] + a[:, :, 2] / 256 - 32768
# a few isolated pixels in the tiles are wrong (below sea level); a 3 x 3 median removes them
from scipy import ndimage as ndi

mosaic = ndi.median_filter(mosaic, size=3, mode='nearest')
n = 2 ** Z


def elevation(lat, lon):
    px = ((lon + 180) / 360 * n - xt[0]) * 256
    py = ((1 - math.log(math.tan(math.radians(lat)) + 1 / math.cos(math.radians(lat))) / math.pi) / 2 * n - yt[0]) * 256
    px = min(max(px - 0.5, 0), mosaic.shape[1] - 1.001)
    py = min(max(py - 0.5, 0), mosaic.shape[0] - 1.001)
    i, j = int(px), int(py)
    fx, fy = px - i, py - j
    m = mosaic
    return (m[j, i] * (1 - fx) * (1 - fy) + m[j, i + 1] * fx * (1 - fy)
            + m[j + 1, i] * (1 - fx) * fy + m[j + 1, i + 1] * fx * fy)


x0, y0 = math.floor(min(xs)) - 1, math.floor(min(ys)) - 1
nx, ny = math.ceil(max(xs)) + 1 - x0, math.ceil(max(ys)) + 1 - y0
grid = np.zeros((ny, nx))
for j in range(ny):
    for i in range(nx):
        lat, lon = unproject(x0 + (i + 0.5) * CELL, y0 + (j + 0.5) * CELL)
        grid[j, i] = elevation(lat, lon)

# the datum: the median elevation inside the province
from matplotlib.path import Path
inside = np.zeros_like(grid, bool)
paths = [Path(r) for r in rings]
for j in range(ny):
    for i in range(nx):
        pt = (x0 + (i + 0.5) * CELL, y0 + (j + 0.5) * CELL)
        inside[j, i] = any(p.contains_point(pt) for p in paths)
datum = float(np.median(grid[inside]))
data = np.clip(np.round(grid / STEP), 0, 255).astype(np.uint8)
print('grid', nx, ny, 'elevation', round(float(grid[inside].min())), round(float(grid[inside].max())),
      'datum', round(datum), 'max byte', int(data.max()))

with open('src/lib/geothermal/terrain-data.ts', 'w') as f:
    f.write(f'''/**
 * Relief of Vojvodina: elevation above sea level on a 1 km grid, from Terrain Tiles on
 * AWS (zoom 8; elevation from SRTM and other sources listed at
 * https://github.com/tilezen/joerd/blob/master/docs/attribution.md).
 *
 * Columns start at x = {x0} km and rows at y = {y0} km (local coordinates, see
 * `ORIGIN` in field.ts), rows running from south to north. A byte is the elevation in
 * steps of {STEP:g} m. `datum` is the median elevation inside the province, the level
 * the model draws as zero.
 *
 * Generated by `scripts/build-terrain-data.py`; do not edit by hand.
 */

export const TERRAIN_GRID = {{ x0: {x0}, y0: {y0}, cell: {CELL:g}, nx: {nx}, ny: {ny}, step: {STEP:g}, datum: {round(datum)} }} as const;

export const TERRAIN_DATA =
  '{base64.b64encode(data.tobytes()).decode()}';
''')
print('written')
